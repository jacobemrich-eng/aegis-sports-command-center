'use strict';

const fs = require('node:fs');
const path = require('node:path');
const engine = require('../src/engine');

const OUTPUT = path.join(__dirname, '..', 'cloudflare', 'generated', 'registry.js');

function generateRegistrySource() {
  const banner = '// Generated by scripts/build-cloudflare-registry.js. Do not edit by hand.\n';
  return banner +
    `export const ENGINE_VERSION = ${JSON.stringify(engine.VERSION)};\n` +
    `export const MODELS = ${JSON.stringify(engine.MODELS, null, 2)};\n` +
    `export const SPORTS = ${JSON.stringify(engine.SPORTS, null, 2)};\n`;
}

function checkRegistry() {
  const expected = generateRegistrySource();
  const actual = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (actual !== expected) {
    console.error('Cloudflare registry is stale. Run: node scripts/build-cloudflare-registry.js');
    return false;
  }
  return true;
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!checkRegistry()) process.exitCode = 1;
  } else {
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, generateRegistrySource());
    console.log('Generated cloudflare/generated/registry.js');
  }
}

module.exports = { OUTPUT, generateRegistrySource, checkRegistry };
